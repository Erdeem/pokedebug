function Assert-True([bool]$Condition, [string]$Message) {
    if (-not $Condition) { throw $Message }
}

function Test-PowerShellSyntax([string]$Path) {
    $errors = $null
    [Management.Automation.Language.Parser]::ParseFile($Path, [ref]$null, [ref]$errors) | Out-Null
    Assert-True ($errors.Count -eq 0) ("PowerShell parser error in {0}: {1}" -f $Path, $errors[0].Message)
}

function Invoke-RubySyntax([string]$RubyPath, [string]$Path) {
    $output = & $RubyPath -c $Path 2>&1
    if ($LASTEXITCODE -ne 0) { throw ("Ruby parser error in {0}: {1}" -f $Path, ($output -join [Environment]::NewLine)) }
}

