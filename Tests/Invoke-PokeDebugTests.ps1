    $utf8 = New-Object Text.UTF8Encoding $false
    $originalGameRb = "RubyVM::InstructionSequence.load_from_binary(File.binread('Game.yarb')).eval`r`n"
    [IO.File]::WriteAllText((Join-Path $psdkFixture "Game.rb"), $originalGameRb, $utf8)
