Write-Host "[8/8] Yuri RGSS chunk generation integration" -ForegroundColor Cyan
$yuriFixture = Join-Path ([IO.Path]::GetTempPath()) ("PokeDebug_YuriFixture_" + [guid]::NewGuid().ToString("N"))
try {
    [void](New-Item -ItemType Directory -Path $yuriFixture -Force)
    $menuContent = [IO.File]::ReadAllText($generatedPath, [Text.Encoding]::UTF8)
    
    $installPs1Path = Join-Path $SourceDir "Install.ps1"
    $installTokens = $null
    $installErrors = $null
    $installAst = [Management.Automation.Language.Parser]::ParseFile($installPs1Path, [ref]$installTokens, [ref]$installErrors)
    Assert-True ($installErrors.Count -eq 0) "Install.ps1 parser error during Yuri chunk test."
    
    $yuriFuncAst = $installAst.Find({
        param($node)
        $node -is [Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq "Write-YuriMenuChunks"
    }, $true)
    Assert-True ($null -ne $yuriFuncAst) "Write-YuriMenuChunks function not found in Install.ps1."
    
    $atomicFuncAst = $installAst.Find({
        param($node)
        $node -is [Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq "Write-Utf8FileAtomic"
    }, $true)
    Assert-True ($null -ne $atomicFuncAst) "Write-Utf8FileAtomic function not found in Install.ps1."
    
    . ([scriptblock]::Create($atomicFuncAst.Extent.Text))
    . ([scriptblock]::Create($yuriFuncAst.Extent.Text))

    # Exercise both strict JSON and the commented MKXP template fallback.
    foreach ($functionName in @('Get-MkxpActiveText', 'Remove-MkxpPreloadScript', 'Update-MkxpPreload', 'Add-MkxpPreloadScript')) {
        $functionAst = $installAst.Find({
            param($node)
            $node -is [Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq $functionName
        }, $true)
        . ([scriptblock]::Create($functionAst.Extent.Text))
    }
    $configPath = Join-Path $yuriFixture 'mkxp.json'
    foreach ($attributes in @([IO.FileAttributes]::Hidden, ([IO.FileAttributes]::Hidden -bor [IO.FileAttributes]::ReadOnly))) {
        foreach ($config in @('{"preloadScript":["existing.rb"]}', "{`r`n// template`r`n`"preloadScript`": [`"existing.rb`"]`r`n}")) {
            if ([IO.File]::Exists($configPath)) { Remove-Item -LiteralPath $configPath -Force }
            [IO.File]::WriteAllText($configPath, $config)
            [IO.File]::SetAttributes($configPath, $attributes)
            $result = Update-MkxpPreload $configPath
            Assert-True $result.Changed 'Protected MKXP config was not updated.'
            Assert-True ([IO.File]::ReadAllText($configPath).Contains('existing.rb')) 'Existing preload was lost.'
            Assert-True ([IO.File]::ReadAllText($configPath).Contains('preload_menu.rb')) 'Menu preload was not added.'
            Assert-True (([IO.File]::GetAttributes($configPath)) -eq $attributes) 'Config attributes changed.'
            Assert-True (-not (Update-MkxpPreload $configPath).Changed) 'Repeated update was not idempotent.'
            [void](Add-MkxpPreloadScript $configPath 'extra.rb')
            Assert-True (Remove-MkxpPreloadScript $configPath 'extra.rb') 'Protected preload removal failed.'
        }
    }
    $originalConfig = [IO.File]::ReadAllText($configPath)
    $lockedFile = [IO.File]::Open($configPath, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::Read)
    try {
        $writeFailed = $false
        try { Write-Utf8FileAtomic $configPath '{}' } catch { $writeFailed = $true }
        Assert-True $writeFailed 'Locked config write unexpectedly succeeded.'
        Assert-True ([IO.File]::ReadAllText($configPath) -eq $originalConfig) 'Failed write damaged config.'
        Assert-True (([IO.File]::GetAttributes($configPath)) -eq $attributes) 'Failed write changed attributes.'
    } finally { $lockedFile.Dispose() }
    
    $chunkCount = Write-YuriMenuChunks -MenuContent $menuContent -DestinationDirectory $yuriFixture
    Assert-True ($chunkCount -ge 20) "Yuri chunk count is unexpectedly small ($chunkCount)."
    
    $chunkFiles = @(Get-ChildItem -LiteralPath $yuriFixture -Filter "*.rb" -File)
    Assert-True ($chunkFiles.Count -eq $chunkCount) "Generated chunk file count mismatch."
    
    if ($ruby) {
        foreach ($chunk in $chunkFiles) {
            Invoke-RubySyntax $ruby.Source $chunk.FullName
        }
    }
} finally {
    $tempRoot = [IO.Path]::GetFullPath([IO.Path]::GetTempPath())
    $resolvedFixture = [IO.Path]::GetFullPath($yuriFixture)
    $safeFixture = $resolvedFixture.StartsWith($tempRoot, [StringComparison]::OrdinalIgnoreCase) -and
        (Split-Path $resolvedFixture -Leaf) -like "PokeDebug_YuriFixture_*"
    if ($safeFixture -and (Test-Path -LiteralPath $resolvedFixture)) {
        Remove-Item -LiteralPath $resolvedFixture -Recurse -Force
    }
}

