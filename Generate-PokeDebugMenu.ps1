$ErrorActionPreference = "Stop"

$sourceDir = Join-Path $PSScriptRoot "Source Code"
$outputPath = Join-Path $sourceDir "pokedebug_menu.rb"
$moduleOrder = @(
    "00_header.rb", "10_core_01_runtime.rb", "10_core_02_engine_player.rb",
    "10_core_03_pokemon.rb", "10_core_04_stats_items.rb", "10_core_05_battles_world.rb",
    "10_core_06_search_ui.rb", "11_input_and_mobile.rb", "12_menu_helpers.rb",
    "13_status_and_summaries.rb", "14_engine_profile.rb", "15_battle_access.rb",
    "16_reports_and_extras.rb", "17_engine_adapters.rb", "18_pokedebug_device.rb",
    "19_psdk_adapter.rb",
    "20_engine.rb", "30_pokemon_items_player.rb", "40_party.rb",
    "45_battle_tools.rb", "50_runtime_patches.rb", "60_psdk_runtime.rb"
)

$missing = $moduleOrder | Where-Object { -not (Test-Path -LiteralPath (Join-Path $sourceDir $_) -PathType Leaf) }
if ($missing) { throw "Missing Ruby module files: $($missing -join ', ')" }

$encoding = New-Object Text.UTF8Encoding $false
$writer = New-Object IO.StreamWriter($outputPath, $false, $encoding)
try {
    $writer.WriteLine("# This file is generated by Generate-PokeDebugMenu.ps1.")
    $writer.WriteLine("# Edit the module files in Source Code instead of editing this file directly.")
    $writer.WriteLine("")
    foreach ($moduleName in $moduleOrder) {
        $writer.WriteLine("# --- BEGIN $moduleName ---")
        $moduleText = [IO.File]::ReadAllText((Join-Path $sourceDir $moduleName), [Text.Encoding]::UTF8).TrimEnd()
        $writer.WriteLine($moduleText)
        $writer.WriteLine("# --- END $moduleName ---")
        $writer.WriteLine("")
    }
} finally {
    $writer.Dispose()
}
Write-Host "[OK] Generated Source Code\pokedebug_menu.rb." -ForegroundColor Green
